    <script>
        // Mock data
        const mockDocument = {
            id: 1,
            name: "Proposal KP - PT Telkom Indonesia",
            category: "proposal",
            description: "Proposal untuk kerja praktik di PT Telkom Indonesia",
            status: "revision",
            version: "1.2",
            file_size: 2048576,
            created_at: "2026-11-07T08:30:00Z",
            updated_at: "2026-11-07T14:20:00Z",
            download_url: "#",
            versions: [
                { version: "1.0", uploaded_at: "2026-11-07T08:30:00Z", status: "draft" },
                { version: "1.1", uploaded_at: "2026-11-07T10:15:00Z", status: "submitted" },
                { version: "1.2", uploaded_at: "2026-11-07T14:20:00Z", status: "revision" }
            ],
            feedback: [
                {
                    id: 1,
                    message: "Perbaiki BAB 2, tambahkan referensi dari tahun 2024-2026",
                    type: "revision",
                    given_by: "dosen@test.com",
                    created_at: "2026-11-07T13:00:00Z"
                }
            ]
        };

        const categoryNames = {
            'proposal': 'Proposal KP',
            'surat_pengantar': 'Surat Pengantar',
            'surat_balasan': 'Surat Balasan',
            'laporan': 'Laporan KP',
            'lembar_bimbingan': 'Lembar Bimbingan',
            'dokumen_revisi': 'Dokumen Revisi',
            'lembar_penilaian': 'Lembar Penilaian',
            'dokumen_pendukung': 'Dokumen Pendukung'
        };

        const statusLabels = {
            'draft': 'Draft',
            'submitted': 'Diajukan',
            'reviewed': 'Diperiksa',
            'revision': 'Revisi',
            'approved': 'Disetujui',
            'archived': 'Arsip'
        };

        document.addEventListener('DOMContentLoaded', () => {
            loadDocumentDetail();
        });

        function loadDocumentDetail() {
            const doc = mockDocument;
            
            // Header
            document.getElementById('docName').textContent = doc.name;
            document.getElementById('docStatus').textContent = statusLabels[doc.status];
            document.getElementById('docStatus').className = `badge ${getBadgeClass(doc.status)}`;
            document.getElementById('docCategory').textContent = categoryNames[doc.category];
            document.getElementById('docFileSize').textContent = formatBytes(doc.file_size);
            document.getElementById('docVersion').textContent = `v${doc.version}`;
            document.getElementById('docCreatedAt').textContent = formatDate(doc.created_at);
            document.getElementById('docUpdatedAt').textContent = formatDate(doc.updated_at);

            // Sidebar
            document.getElementById('infoCategory').textContent = categoryNames[doc.category];
            document.getElementById('infoStatus').textContent = statusLabels[doc.status];
            document.getElementById('infoDescription').textContent = doc.description || '-';

            // Show/hide buttons based on status
            if (doc.status === 'draft') {
                document.getElementById('submitBtn').style.display = 'block';
                document.getElementById('uploadNewBtn').style.display = 'block';
                document.getElementById('deleteBtn').style.display = 'block';
            } else if (doc.status === 'revision') {
                document.getElementById('revisionBtn').style.display = 'block';
            }

            renderVersions(doc.versions);
            renderFeedback(doc.feedback);
        }

        function renderVersions(versions) {
            const list = document.getElementById('versionsList');
            // Safe: Trusting versions array from app state, escaping in template
            list.innerHTML = versions.map((v, idx) => `
                <div class="timeline-item">
                    <div class="timeline-marker">
                        <i class="bi bi-file-earmark-check"></i>
                    </div>
                    <div class="timeline-content">
                        <h6 class="mb-1">v${v.version} <span class="badge badge-sm">${escapeHtml(statusLabels[v.status])}</span></h6>
                        <p class="text-muted mb-2">${formatDate(v.uploaded_at)}</p>
                        <button class="btn btn-sm btn-outline-primary" onclick="downloadVersion('${v.version}')">
                            <i class="bi bi-download"></i> Download
                        </button>
                    </div>
                </div>
            `).join('');
        }

        function renderFeedback(feedbacks) {
            const list = document.getElementById('feedbackList');
            if (feedbacks.length === 0) {
                list.textContent = 'Belum ada feedback'; // Safe: textContent
                return;
            }

            // Safe: Create DOM elements instead of innerHTML
            list.innerHTML = '';
            feedbacks.forEach(f => {
                const div = document.createElement('div');
                div.className = 'feedback-item mb-3 pb-3 border-bottom';
                div.innerHTML = `
                    <div class="d-flex justify-content-between mb-2">
                        <strong>${escapeHtml(f.given_by)}</strong>
                        <small class="text-muted">${formatDate(f.created_at)}</small>
                    </div>
                    <p class="badge mb-2">${escapeHtml(f.type.charAt(0).toUpperCase() + f.type.slice(1))}</p>
                `;
                const msgP = document.createElement('p');
                msgP.textContent = f.message; // Safe: textContent for user input
                div.appendChild(msgP);
                list.appendChild(div);
            });
        }

        function escapeHtml(text) {
            const map = {
                '&': '&amp;',
                '<': '&lt;',
                '>': '&gt;',
                '"': '&quot;',
                "'": '&#039;'
            };
            return text.replace(/[&<>"']/g, m => map[m]);
        }

        function getBadgeClass(status) {
            const classes = {
                'draft': 'badge-draft',
                'submitted': 'badge-submitted',
                'revision': 'badge-revision',
                'approved': 'badge-approved',
                'archived': 'badge-archived'
            };
            return classes[status] || 'badge-secondary';
        }

        function downloadDocument() {
            showToast('Mengunduh dokumen...', 'info');
        }

        function uploadNewVersion() {
            showToast('Membuka upload modal...', 'info');
        }

        function deleteDocument() {
            if (confirm('Hapus dokumen ini?')) {
                showToast('Dokumen dihapus', 'success');
                window.location.href = '/documents';
            }
        }

        function submitDocument() {
            if (confirm('Ajukan dokumen untuk pemeriksaan?')) {
                showToast('Dokumen berhasil diajukan', 'success');
                setTimeout(() => location.reload(), 1500);
            }
        }

        function downloadVersion(version) {
            showToast(`Mengunduh v${version}...`, 'info');
        }
    </script>
